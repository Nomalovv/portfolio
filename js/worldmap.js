var MAP_W = 1600, MAP_H = 800;

function buildWorldMap() {
  var cv = document.createElement('canvas');
  cv.width = MAP_W; cv.height = MAP_H;
  var g = cv.getContext('2d');
  g.fillStyle = '#000'; g.fillRect(0, 0, MAP_W, MAP_H);

  // Projection équirectangulaire : lon [-180,180] -> x, lat [90,-90] -> y
  function px(lon) { return (lon + 180) / 360 * MAP_W; }
  function py(lat) { return (90 - lat) / 180 * MAP_H; }

  function trace(flat) {
    g.beginPath();
    g.moveTo(px(flat[0]), py(flat[1]));
    for (var i = 2; i < flat.length; i += 2) g.lineTo(px(flat[i]), py(flat[i + 1]));
    g.closePath();
  }

  g.fillStyle = '#fff';
  g.strokeStyle = '#fff';
  g.lineJoin = 'round';
  for (var i = 0; i < LAND.length; i++) {
    trace(LAND[i]);
    g.fill();
    // Un léger trait épaissit les péninsules trop fines pour survivre à l'échantillonnage
    g.lineWidth = 3;
    g.stroke();
  }
  g.fillStyle = '#000';
  for (var s = 0; s < SEAS.length; s++) { trace(SEAS[s]); g.fill(); }

  return g.getImageData(0, 0, MAP_W, MAP_H);
}

/* Conversion lat/lon -> position cartésienne sur une sphère de rayon r.
   Convention retenue : lon 0 vers +Z, lon 90°E vers +X. */
function latLonToVec3(lat, lon, r) {
  var phi = (90 - lat) * Math.PI / 180;
  var theta = lon * Math.PI / 180;
  return new THREE.Vector3(
    r * Math.sin(phi) * Math.sin(theta),
    r * Math.cos(phi),
    r * Math.sin(phi) * Math.cos(theta)
  );
}

/* ============================================================================
   2. TEXTURES GÉNÉRÉES (disque doux, anneau radar, halo bokeh)
   ========================================================================== */
function texDisc(soft) {
  var c = document.createElement('canvas'); c.width = c.height = 64;
  var g = c.getContext('2d');
  var gr = g.createRadialGradient(32, 32, 0, 32, 32, 32);
  if (soft) {
    // Disque des points de terre : noyau plein, bord adouci. Un dégradé trop
    // progressif rendrait les points quasi invisibles à 3 px.
    gr.addColorStop(0.00, 'rgba(255,255,255,1)');
    gr.addColorStop(0.32, 'rgba(255,255,255,1)');
    gr.addColorStop(0.58, 'rgba(255,255,255,0.55)');
    gr.addColorStop(0.82, 'rgba(255,255,255,0.10)');
    gr.addColorStop(1.00, 'rgba(255,255,255,0)');
  } else {
    gr.addColorStop(0.00, 'rgba(255,255,255,1)');
    gr.addColorStop(0.22, 'rgba(255,255,255,0.75)');
    gr.addColorStop(0.55, 'rgba(255,255,255,0.16)');
    gr.addColorStop(1.00, 'rgba(255,255,255,0)');
  }
  g.fillStyle = gr; g.fillRect(0, 0, 64, 64);
  var t = new THREE.CanvasTexture(c);
  t.needsUpdate = true;
  return t;
}
function texRing() {
  var c = document.createElement('canvas'); c.width = c.height = 128;
  var g = c.getContext('2d');
  var gr = g.createRadialGradient(64, 64, 0, 64, 64, 64);
  gr.addColorStop(0.00, 'rgba(255,255,255,0)');
  gr.addColorStop(0.62, 'rgba(255,255,255,0)');
  gr.addColorStop(0.80, 'rgba(255,255,255,0.75)');
  gr.addColorStop(0.92, 'rgba(255,255,255,0.22)');
  gr.addColorStop(1.00, 'rgba(255,255,255,0)');
  g.fillStyle = gr; g.fillRect(0, 0, 128, 128);
  var t = new THREE.CanvasTexture(c); t.needsUpdate = true; return t;
}
function texBokeh() {
  var c = document.createElement('canvas'); c.width = c.height = 256;
  var g = c.getContext('2d');
  var gr = g.createRadialGradient(128, 128, 20, 128, 128, 128);
  gr.addColorStop(0.00, 'rgba(255,255,255,0.30)');
  gr.addColorStop(0.55, 'rgba(255,255,255,0.16)');
  gr.addColorStop(0.86, 'rgba(255,255,255,0.05)');
  gr.addColorStop(1.00, 'rgba(255,255,255,0)');
  g.fillStyle = gr; g.beginPath(); g.arc(128, 128, 128, 0, Math.PI * 2); g.fill();
  var t = new THREE.CanvasTexture(c); t.needsUpdate = true; return t;
}

